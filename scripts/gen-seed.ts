// Builds the Freerange Library from src/lib/library/content/*.json:
// - src/lib/library/catalog.json and loaders.ts, which the app bundles;
// - supabase/seed.sql, which loads the Library into the database
//   (`supabase db reset` locally; `supabase db push --include-seed` in
//   production). Every statement is an upsert, so it's safe to run again.
// Run: npm run library:gen
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

import { catalogEntry, libraryContent, libraryListing, type LibraryEntry } from '../src/lib/library/build.ts';

const dir = new URL('../src/lib/library/', import.meta.url);
const files = readdirSync(new URL('content/', dir)).filter((f) => f.endsWith('.json')).sort();
const entries = files.map((f) => JSON.parse(readFileSync(new URL(`content/${f}`, dir), 'utf8')) as LibraryEntry);
for (const [i, e] of entries.entries()) if (`${e.key}.json` !== files[i]) throw new Error(`${files[i]}: key is "${e.key}"`);

const catalog = entries.map(catalogEntry);
writeFileSync(new URL('catalog.json', dir), `${JSON.stringify(catalog)}\n`);
writeFileSync(
  new URL('loaders.ts', dir),
  [
    '// Generated by scripts/gen-seed.ts (npm run library:gen). Each import becomes its own web bundle.',
    'export const LOADERS: Record<string, () => Promise<unknown>> = {',
    ...entries.map((e) => `  '${e.key}': () => import('./content/${e.key}.json'),`),
    '};',
    '',
  ].join('\n'),
);

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v)) return `array[${v.map(q).join(', ')}]::text[]`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (v: string[]) => (v.length ? q(v) : `'{}'::text[]`);
const js = (v: unknown) => (v === undefined || v === null ? 'null' : `${q(JSON.stringify(v))}::jsonb`);

const cols = ['id', 'seller_name', 'seller_kind', 'seller_verified', 'title', 'subjects', 'grade_min', 'grade_max', 'philosophies', 'format', 'price', 'description', 'includes', 'lessons', 'lessons_per_week', 'minutes_per_lesson', 'parent_involvement', 'family_style', 'lesson_steps', 'cover', 'color', 'esa_eligible', 'created_at', 'package_id', 'package_version', 'license', 'attribution', 'outline'];
const lines: string[] = [
  '-- Generated by scripts/gen-seed.ts (npm run library:gen) — the Freerange Library.',
  '-- Free curricula (public domain or openly licensed) converted into lesson plans.',
  '',
];
entries.forEach((e, i) => {
  const l = libraryListing(catalog[i]);
  const values = [q(l.id), q(l.seller), q(l.sellerKind), q(l.sellerVerified), q(l.title), arr(l.subjects), l.gradeMin, l.gradeMax, arr(l.philosophies), q(l.format), l.price, q(l.description), arr(l.includes), l.lessons, l.lessonsPerWeek, l.minutesPerLesson, q(l.parentInvolvement), q(l.familyStyle), arr(l.lessonSteps), q(l.cover), q(l.color), q(l.esaEligible), q(l.createdAt), q(l.packageId), l.packageVersion!, js(l.license), q(l.attribution), js(l.outline)];
  lines.push(
    `insert into public.listings (${cols.join(', ')}) values (${values.join(', ')})\n  on conflict (id) do update set ${cols.filter((c) => c !== 'id' && c !== 'created_at').map((c) => `${c} = excluded.${c}`).join(', ')};`,
    `insert into public.package_releases (listing_id, version, content) values (${q(l.id)}, ${l.packageVersion!}, ${js(libraryContent(e))})\n  on conflict (listing_id, version) do update set content = excluded.content;`,
  );
});
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), `${lines.join('\n')}\n`);
console.log(`Library: ${entries.length} curricula, ${catalog.reduce((n, c) => n + c.lessons, 0)} lessons`);
